// ─────────────────────────────────────────────────────────
// In-memory rolling failure tracker for alert throttling.
// Persists for the lifetime of a warm Vercel lambda (~15 min idle).
// Cold start resets it. Accept this — for Mason's volume the trade-off
// is right. Swap to Upstash Redis if alert reliability becomes critical.
// ─────────────────────────────────────────────────────────
const failureLog = []; // array of timestamps (ms) within last hour
let lastAlertSentAt = 0;
const ONE_HOUR_MS = 60 * 60 * 1000;
const FAILURE_THRESHOLD = 3;

function recordFailureAndMaybeAlert(context) {
  const now = Date.now();
  // Prune entries older than 1 hour
  while (failureLog.length && now - failureLog[0] > ONE_HOUR_MS) {
    failureLog.shift();
  }
  failureLog.push(now);

  if (failureLog.length >= FAILURE_THRESHOLD && now - lastAlertSentAt > ONE_HOUR_MS) {
    lastAlertSentAt = now;
    // Fire and forget — don't block webhook response on alert delivery
    sendFailureAlert(failureLog.length, context).catch(err => {
      console.error('Alert email failed to send:', err);
    });
  }
}

async function sendFailureAlert(count, context) {
  const apiKey = process.env.RESEND_API_KEY;
  const alertTo = process.env.ALERT_EMAIL;
  if (!apiKey || !alertTo) {
    console.error('Cannot send alert — missing RESEND_API_KEY or ALERT_EMAIL');
    return;
  }

  const body = `Mason beehiiv \u2192 Resend sync has logged ${count} failures in the past hour.

Latest failure context:
${JSON.stringify(context, null, 2)}

Check Vercel logs for the full picture:
https://vercel.com/dashboard \u2192 readmason \u2192 Logs \u2192 /api/beehiiv-webhook

This alert is throttled to once per hour.`;

  await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      from: 'Mason Alerts <newsletter@readmason.com>',
      to: [alertTo],
      subject: `Mason sync alert: ${count} failures in past hour`,
      text: body,
    }),
  });
}

// ─────────────────────────────────────────────────────────
// Verify beehiiv webhook signature.
// beehiiv signs requests using HMAC-SHA256 with the webhook secret.
// The signature is delivered via the `svix-signature` header (beehiiv uses
// Svix as their webhook delivery layer). If the header shape changes, log
// the raw headers on the first hit and we'll tighten this.
// ─────────────────────────────────────────────────────────
function verifyBeehiivSignature(req, rawBody) {
  const secret = process.env.BEEHIIV_WEBHOOK_SECRET;
  if (!secret) {
    console.error('BEEHIIV_WEBHOOK_SECRET not set');
    return false;
  }

  const svixId = req.headers['svix-id'];
  const svixTimestamp = req.headers['svix-timestamp'];
  const svixSignature = req.headers['svix-signature'];

  if (!svixId || !svixTimestamp || !svixSignature) {
    console.warn('Missing svix-* headers — rejecting');
    return false;
  }

  // Svix signs: `${svix_id}.${svix_timestamp}.${body}`
  // Secret is base64-encoded, prefixed with "whsec_"
  try {
    const secretBytes = Buffer.from(secret.replace(/^whsec_/, ''), 'base64');
    const signedPayload = `${svixId}.${svixTimestamp}.${rawBody}`;
    const expected = crypto
      .createHmac('sha256', secretBytes)
      .update(signedPayload)
      .digest('base64');

    // svixSignature is space-separated list like "v1,abc123 v1,def456"
    // Any signature matching is sufficient (Svix rotates them)
    const sigs = svixSignature.split(' ').map(s => s.split(',')[1]);
    return sigs.some(sig => {
      try {
        return crypto.timingSafeEqual(
          Buffer.from(sig, 'base64'),
          Buffer.from(expected, 'base64')
        );
      } catch {
        return false;
      }
    });
  } catch (err) {
    console.error('Signature verification threw:', err);
    return false;
  }
}

// ─────────────────────────────────────────────────────────
// Check if a contact already exists in Resend.
// Returns: { exists: bool, error: optional }
// ─────────────────────────────────────────────────────────
async function resendContactExists(email) {
  const apiKey = process.env.RESEND_API_KEY;
  const segmentId = process.env.RESEND_SEGMENT_ID;
  try {
    const r = await fetch(
      `https://api.resend.com/audiences/${segmentId}/contacts/${encodeURIComponent(email)}`,
      {
        method: 'GET',
        headers: { 'Authorization': `Bearer ${apiKey}` },
      }
    );
    if (r.ok) return { exists: true };
    if (r.status === 404) return { exists: false };
    // Some other error — treat as not-exists but log it
    const txt = await r.text();
    console.warn('Resend contact lookup non-200:', r.status, txt);
    return { exists: false, error: `${r.status} ${txt}` };
  } catch (err) {
    console.error('Resend contact lookup threw:', err);
    return { exists: false, error: err.message };
  }
}

// ─────────────────────────────────────────────────────────
// Add a contact to the Resend segment.
// Mirrors the schema used in /api/subscribe.js — only fields Resend's
// audience properties schema actually accepts.
// ─────────────────────────────────────────────────────────
async function addToResend(email, sourceLabel) {
  const apiKey = process.env.RESEND_API_KEY;
  const segmentId = process.env.RESEND_SEGMENT_ID;

  const r = await fetch('https://api.resend.com/contacts', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      email,
      unsubscribed: false,
      segments: [{ id: segmentId }],
      // NOTE: Resend rejects arbitrary properties (422). Stick to the same
      // fields /api/subscribe.js uses. We encode the source into `industry`
      // as a temporary tag carrier — re-evaluate if Resend adds tag support.
      properties: {
        role: '',
        company_size: '',
        industry: `beehiiv:${sourceLabel}`,
        country: '',
      },
    }),
  });

  if (!r.ok) {
    const errText = await r.text();
    throw new Error(`Resend contact create failed: ${r.status} ${errText}`);
  }
  return true;
}

