// Send the Boost welcome email via Resend.
// ─────────────────────────────────────────────────────────
async function sendBoostWelcomeEmail(email) {
  const apiKey = process.env.RESEND_API_KEY;
  const r = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      from: 'Mason <newsletter@readmason.com>',
      to: [email],
      reply_to: 'newsletter@readmason.com',
      subject: "Welcome to Mason \u2014 here's a free book",
      html: BOOST_WELCOME_HTML,
    }),
  });
  if (!r.ok) {
    const errText = await r.text();
    throw new Error(`Resend email send failed: ${r.status} ${errText}`);
  }
  return true;
}

// ─────────────────────────────────────────────────────────
// Read raw body — required for signature verification because Vercel's
// default JSON parser strips the original bytes used in the HMAC.
// ─────────────────────────────────────────────────────────
export const config = {
  api: {
    bodyParser: false,
  },
};

async function readRawBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    req.on('data', c => chunks.push(c));
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

// ─────────────────────────────────────────────────────────
// Main handler
// ─────────────────────────────────────────────────────────
export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  let rawBody;
  try {
    rawBody = await readRawBody(req);
  } catch (err) {
    console.error('Failed to read request body:', err);
    return res.status(400).json({ error: 'Bad request body' });
  }

  // Signature verification
  if (!verifyBeehiivSignature(req, rawBody)) {
    console.warn('Invalid webhook signature — rejecting');
    return res.status(401).json({ error: 'Invalid signature' });
  }

  let payload;
  try {
    payload = JSON.parse(rawBody);
  } catch (err) {
    console.error('Failed to parse webhook JSON:', err);
    return res.status(400).json({ error: 'Invalid JSON' });
  }

  // Log every webhook hit at least once so we can see the shape beehiiv
  // is sending. Remove or downgrade to debug after first prod payloads.
  console.log('beehiiv webhook received:', JSON.stringify(payload).slice(0, 1000));

  // beehiiv wraps events as: { event_type, id, created, data: { ... } }
  // We defend against both wrapped and flat shapes.
  const eventType = payload.event_type || payload.type;
  const data = payload.data || payload;

  // Only act on subscription creation events.
  // Accept several known event-type strings to be tolerant of doc drift.
  const isCreateEvent = !eventType
    || /subscription[._-]?created/i.test(eventType)
    || /subscriber[._-]?created/i.test(eventType);
  if (!isCreateEvent) {
    console.log('Ignoring non-create event:', eventType);
    return res.status(200).json({ status: 'ignored', reason: 'not a create event' });
  }

  const email = (data.email || '').toLowerCase().trim();
  if (!email || !email.includes('@')) {
    console.warn('Webhook missing valid email:', data);
    return res.status(200).json({ status: 'skipped', reason: 'no email' });
  }

  // Detect "this came from /api/subscribe" — those subs are already in Resend.
  // /api/subscribe.js sets utm_source: 'readmason.com' on every beehiiv write.
  const utmSource = data.utm_source || '';
  const utmCampaign = data.utm_campaign || '';
  const referringSite = data.referring_site || '';
  const cameFromOurForm =
    utmSource === 'readmason.com' ||
    referringSite === 'https://readmason.com' ||
    referringSite === 'readmason.com';

  if (cameFromOurForm) {
    return res.status(200).json({ status: 'skipped', reason: 'originated from /api/subscribe' });
  }

  // Build a human-readable source label for tagging in Resend.
  // beehiiv typically populates one of: subscription_premium_tier_changes,
  // boosts, recommendations, referrals, or organic.
  const sourceLabel =
    data.source ||
    data.subscription_source ||
    utmSource ||
    utmCampaign ||
    'beehiiv-native';

  // Dedup check — don't double-write or re-welcome.
  const dedup = await resendContactExists(email);
  if (dedup.exists) {
    return res.status(200).json({ status: 'skipped', reason: 'already in Resend' });
  }

  // Write to Resend + send welcome.
  try {
    await addToResend(email, sourceLabel);
  } catch (err) {
    console.error('addToResend failed:', err.message);
    recordFailureAndMaybeAlert({ stage: 'addToResend', email, source: sourceLabel, err: err.message });
    // Graceful degradation: return 200 so beehiiv doesn't retry forever.
    return res.status(200).json({ status: 'error', stage: 'resend-add', error: err.message });
  }

  try {
    await sendBoostWelcomeEmail(email);
  } catch (err) {
    console.error('sendBoostWelcomeEmail failed:', err.message);
    recordFailureAndMaybeAlert({ stage: 'sendBoostWelcomeEmail', email, source: sourceLabel, err: err.message });
    return res.status(200).json({ status: 'error', stage: 'welcome-email', error: err.message });
  }

  console.log('beehiiv sync OK:', email, 'source:', sourceLabel);
  return res.status(200).json({ status: 'synced', email, source: sourceLabel });
}
